// Writes the public API of the three libraries as markdown: one section per assembly, one list per type.
// Usage: ApiList > docs/api.md
using System.Reflection;
using System.Text;

Assembly[] assemblies =
[
    typeof(OneScope.Sdk.History).Assembly,
    typeof(OneScope.Probe.ScopeProbe).Assembly,
    typeof(OneScope.Attach.ProbeClient).Assembly,
];

var sb = new StringBuilder();
sb.AppendLine("# Public API of the 1.0 libraries");
sb.AppendLine();
sb.AppendLine("Generated by `tools/ApiList` from the built assemblies; every member has an XML doc comment in the source (units, limits, exceptions).");
foreach (Assembly assembly in assemblies)
{
    sb.AppendLine().Append("## ").AppendLine(assembly.GetName().Name);
    foreach (Type type in assembly.GetExportedTypes().OrderBy(t => t.Namespace, StringComparer.Ordinal).ThenBy(t => t.FullName, StringComparer.Ordinal))
    {
        if (type.IsNested)
        {
            continue;
        }

        WriteType(sb, type, 0);
    }
}

Console.Out.Write(sb.ToString());
return 0;

static void WriteType(StringBuilder sb, Type type, int depth)
{
    string kind = type.IsInterface ? "interface" : type.IsEnum ? "enum" : type.IsValueType ? "struct" : type.IsAbstract && type.IsSealed ? "static class" : type.IsAbstract ? "abstract class" : type.IsSealed ? "sealed class" : "class";
    string indent = new(' ', depth * 2);
    sb.AppendLine().Append(indent).Append("### ").Append(depth == 0 ? "" : "nested ").Append(kind).Append(' ').Append('`').Append(Name(type)).Append('`');
    Type? baseType = type.BaseType;
    List<string> bases = [];
    if (baseType is not null && baseType != typeof(object) && baseType != typeof(ValueType) && baseType != typeof(Enum))
    {
        bases.Add(Name(baseType));
    }

    bases.AddRange(type.GetInterfaces().Where(i => i.Namespace != null && i.Namespace.StartsWith("OneScope", StringComparison.Ordinal)).Select(Name));
    if (bases.Count > 0)
    {
        sb.Append(" : ").Append(string.Join(", ", bases));
    }

    sb.AppendLine().AppendLine();
    const BindingFlags flags = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
    if (type.IsEnum)
    {
        sb.Append(indent).Append("Values: ").AppendLine(string.Join(", ", Enum.GetNames(type)));
        return;
    }

    List<string> lines = [];
    foreach (ConstructorInfo c in type.GetConstructors(flags))
    {
        lines.Add($"{type.Name.Split('`')[0]}({Params(c.GetParameters())})");
    }

    foreach (FieldInfo f in type.GetFields(flags))
    {
        lines.Add($"{(f.IsLiteral ? "const " : f.IsStatic ? "static " : "")}{Name(f.FieldType)} {f.Name}");
    }

    foreach (PropertyInfo p in type.GetProperties(flags))
    {
        MethodInfo? get = p.GetMethod, set = p.SetMethod;
        bool isStatic = (get ?? set)!.IsStatic;
        string acc = (get is { IsPublic: true } ? "get; " : "") + (set is { IsPublic: true } ? (IsInit(set) ? "init; " : "set; ") : "");
        string idx = p.GetIndexParameters().Length > 0 ? $"[{Params(p.GetIndexParameters())}]" : "";
        lines.Add($"{(isStatic ? "static " : "")}{Name(p.PropertyType)} {p.Name}{idx} {{ {acc.TrimEnd()} }}");
    }

    foreach (EventInfo e in type.GetEvents(flags))
    {
        lines.Add($"event {Name(e.EventHandlerType!)} {e.Name}");
    }

    foreach (MethodInfo m in type.GetMethods(flags).Where(m => !m.IsSpecialName && !IsGenerated(m)).OrderBy(m => m.Name, StringComparer.Ordinal))
    {
        string generic = m.IsGenericMethod ? $"<{string.Join(", ", m.GetGenericArguments().Select(a => a.Name))}>" : "";
        lines.Add($"{(m.IsStatic ? "static " : "")}{Name(m.ReturnType)} {m.Name}{generic}({Params(m.GetParameters())})");
    }

    foreach (string line in lines)
    {
        sb.Append(indent).Append("- `").Append(line).AppendLine("`");
    }

    foreach (Type nested in type.GetNestedTypes(BindingFlags.Public).OrderBy(t => t.Name, StringComparer.Ordinal))
    {
        WriteType(sb, nested, depth + 1);
    }
}

// Members the compiler writes for records and record structs say nothing a reader needs.
static bool IsGenerated(MethodInfo m) =>
    m.Name.Contains('<', StringComparison.Ordinal)
    || (m.Name is "Equals" or "GetHashCode" or "ToString" or "Deconstruct"
        && m.DeclaringType!.GetMethod("PrintMembers", BindingFlags.NonPublic | BindingFlags.Instance) is not null);

static bool IsInit(MethodInfo set) =>
    set.ReturnParameter.GetRequiredCustomModifiers().Any(t => t.FullName == "System.Runtime.CompilerServices.IsExternalInit");

static string Params(ParameterInfo[] ps) => string.Join(", ", ps.Select(p =>
{
    string prefix = p.IsOut ? "out " : p.ParameterType.IsByRef ? (p.IsIn ? "in " : "ref ") : "";
    Type t = p.ParameterType.IsByRef ? p.ParameterType.GetElementType()! : p.ParameterType;
    string def = p.HasDefaultValue ? " = " + (p.DefaultValue is null ? "default" : p.DefaultValue is bool b ? (b ? "true" : "false") : p.DefaultValue.ToString()) : "";
    return $"{prefix}{Name(t)} {p.Name}{def}";
}));

static string Name(Type t)
{
    if (t.IsArray)
    {
        return Name(t.GetElementType()!) + "[]";
    }

    if (Nullable.GetUnderlyingType(t) is { } u)
    {
        return Name(u) + "?";
    }

    string name = t.Name.Split('`')[0];
    if (t.IsNested)
    {
        name = Name(t.DeclaringType!) + "." + name;
    }

    if (t.IsGenericType)
    {
        name += "<" + string.Join(", ", t.GetGenericArguments().Select(Name)) + ">";
    }

    return name switch { "Int32" => "int", "Int64" => "long", "Boolean" => "bool", "String" => "string", "Byte" => "byte", "Single" => "float", "Double" => "double", "UInt64" => "ulong", "UInt32" => "uint", "Void" => "void", "Object" => "object", "UInt16" => "ushort", "Char" => "char", "Int16" => "short", _ => name };
}
